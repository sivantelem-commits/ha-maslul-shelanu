/* ============================================================
   PASSWORD PROTECTION
   כל פרופיל מוגן בסיסמה שהוא/היא בוחר/ת בעצמו/ה. הסיסמה לא נשמרת
   כטקסט גלוי - נשמר רק hash (טביעת אצבע חד-כיוונית) שלה, כך שגם
   מי שיש לו גישה למסד הנתונים לא רואה את הסיסמה עצמה. זו הגנה
   קלה ונוחה בין שני אנשים שסומכים אחד על השני - לא הצפנה ברמה
   בנקאית, אבל מספיקה כדי שאף אחד אחר לא ייכנס לפרופיל שלא שלו.
============================================================ */
async function hashPassword(name, password){
  const enc = new TextEncoder().encode(`ha-maslul-shelanu:${name}:${password}`);
  const buf = await crypto.subtle.digest('SHA-256', enc);
  return Array.from(new Uint8Array(buf)).map(b=>b.toString(16).padStart(2,'0')).join('');
}
async function getAuthHash(name){
  const a = await sGet(`auth:${name}`);
  return a ? a.hash : null;
}
async function setAuthHash(name, hash){
  await sSet(`auth:${name}`, {hash});
}


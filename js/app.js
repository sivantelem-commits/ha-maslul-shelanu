// כמה ניסוחים שונים למושג אחד (בעיקר ירקות/פירות כלליים) - מאוחדים לשם קנוני אחד
// כדי שלא יופיעו כמה שורות שונות ברשימת הקניות עבור אותו דבר בפועל
const GENERIC_ALIASES = {
  'ירקות מגוונים':'ירקות', 'סלט ירקות':'ירקות', 'ירקות טריים':'ירקות', 'ירקות חתוכים':'ירקות',
  'ירקות מוקפצים':'ירקות', 'ירקות אפויים':'ירקות', 'ירקות מאודים':'ירקות', 'ירקות שורש':'ירקות',
  'סלט ירוק':'ירקות',
  'פרי':'פרי עונה', 'פרי קטן':'פרי עונה', 'פרי לקישוט':'פרי עונה',
};

function canonicalizeName(name){
  let n = name.trim();
  if(PLURAL_MAP[n]) n = PLURAL_MAP[n];
  for(const pre of DESCRIPTOR_PREFIXES){
    const reP = new RegExp('^'+pre+'\\s+');
    if(reP.test(n)){ n = n.replace(reP, '').trim(); break; }
  }
  for(let pass=0; pass<2; pass++){
    for(const suf of DESCRIPTOR_SUFFIXES){
      const re = new RegExp('\\s+'+suf+'$');
      if(re.test(n)){ n = n.replace(re, '').trim(); break; }
    }
  }
  if(PLURAL_MAP[n]) n = PLURAL_MAP[n];
  if(GENERIC_ALIASES[n]) n = GENERIC_ALIASES[n];
  return n.trim();
}

// מפרק מחרוזת מרכיב חופשית לכמות + יחידה + שם מנורמל.
// מחזיר {name, amount, unit} כאשר unit=null אומר "לא ניתן לכמת" (יוצג כרשימה רגילה בלי סכימה)
function parseIngredient(raw){
  let text = raw.trim().replace(/\(.*?\)/g, '').trim(); // הסרת הערות בסוגריים כמו "(כ-280 גרם בשר טחון)"

  // נרמול "כוס וחצי X" / "קופסה וחצי X" / "בטטה וחצי" לצורה "1.5 X" כדי שהפרסינג
  // הרגיל יוכל להתמודד איתה (בלי זה נשארת שארית שבורה כמו "וחצי אורז מלא")
  const halfMatch = text.match(/^(\S+)\s+וחצי\s*(.*)$/);
  if(halfMatch){
    text = `1.5 ${halfMatch[1]}${halfMatch[2] ? ' '+halfMatch[2] : ''}`;
  }

  // 1. מספר רגיל בהתחלה: "120 גרם חזה עוף", "2 ביצים"
  let m = text.match(/^(\d+(?:\.\d+)?)\s+(.*)$/);
  let amount = null, rest = text;
  if(m){
    amount = parseFloat(m[1]);
    rest = m[2];
  } else {
    // 2. מילת שבר בהתחלה: "חצי אבוקדו", "שלושת רבעי כוס..."
    for(const [word, val] of Object.entries(FRACTION_WORDS)){
      if(text.startsWith(word+' ')){
        amount = val;
        rest = text.slice(word.length+1);
        break;
      }
    }
    if(amount===null){
      // 3. מילת מספר בהתחלה: "שני תפוחים"
      for(const [word, val] of Object.entries(NUMBER_WORDS)){
        if(text.startsWith(word+' ')){
          amount = val;
          rest = text.slice(word.length+1);
          break;
        }
      }
    }
    if(amount===null){
      // 4. מילת מספר/שבר בסוף: "פרי אחד", "ביצה קשה אחת"
      for(const [word, val] of Object.entries(NUMBER_WORDS)){
        if(text.endsWith(' '+word)){
          amount = val;
          rest = text.slice(0, text.length-word.length-1);
          break;
        }
      }
    }
  }

  // חילוץ יחידה מתוך "rest" (אם קיימת) - גם אם לא נמצא מספר מפורש קודם
  // (למשל "פרוסת לחם מלא" / "כפית שמן זית" = יחידה בודדת אחת)
  let unit = null;
  for(const [re, u] of UNIT_WORDS){
    if(re.test(rest)){
      unit = u;
      rest = rest.replace(re, '');
      if(amount===null) amount = 1;
      break;
    }
  }

  rest = rest.trim();

  // כף/כפית הן מידות שימוש ממוצר קיים (שמן, תבלינים) - לא כמות שקונים בחנות.
  // מוצגות כתזכורת כללית ברשימה, בלי לסכם "13 כפית שמן זית"
  if(unit && STAPLE_UNITS.includes(unit)){
    return {name: canonicalizeName(rest), amount:null, unit:null};
  }

  if(amount!==null && unit){
    return {name: canonicalizeName(rest), amount, unit};
  }
  if(amount!==null && !unit){
    // מספר בלי יחידת מידה מפורשת - למשל "2 ביצים", "5 שקדים", "3 תמרים"
    return {name: canonicalizeName(rest), amount, unit:'יחידה'};
  }
  // אין מספר בכלל - בדיקה אם זה פריט "בן מנייה" יחיד (עגבנייה פרוסה = עגבנייה אחת)
  for(const noun of SINGLE_COUNTABLE){
    if(rest.startsWith(noun)){
      return {name: canonicalizeName(noun), amount:1, unit:'יחידה'};
    }
  }
  // לא ניתן לכימות (ירקות מגוונים, רוטב עגבניות, תיבול...) - יוצג כפריט רגיל
  return {name: canonicalizeName(text), amount:null, unit:null};
}

const UNIT_PLURALS = {'יחידה':'יחידות','פרוסה':'פרוסות','כוס':'כוסות','גביע':'גביעים','קובייה':'קוביות','גרם':'גרם'};
function unitLabel(unit, amount){
  if(amount===1) return unit;
  return UNIT_PLURALS[unit] || unit;
}

function formatAmount(amount){
  // מציג 0.5/0.25/0.75 כשברים קריאים, ואחרת מעוגל לפי הצורך
  const whole = Math.floor(amount);
  const frac = amount - whole;
  const fracMap = {0.5:'½', 0.25:'¼', 0.75:'¾', 0.34:'⅓', [1/3]:'⅓', 0.125:'⅛'};
  for(const [f, sym] of Object.entries(fracMap)){
    if(Math.abs(frac - f) < 0.02){
      return (whole>0 ? whole+' ' : '') + sym;
    }
  }
  return Number.isInteger(amount) ? String(amount) : amount.toFixed(1);
}

/* ============================================================
   המרה ליחידות קנייה אמיתיות
   הכמויות הגולמיות שנאספות הן ביחידות "צריכה/בישול" (כוס, פרוסה,
   מספר שקדים בודדים) - אבל בחנות לא קונים כוסות אורז או שקד בודד.
   הפונקציה הזו הופכת כמות+יחידה+שם לניסוח שאפשר לקחת איתו לסופר.
============================================================ */
// פריטים "בני מנייה" שבפועל נמכרים במשקל, לא ביחידות בודדות - עם משקל ממוצע ליחידה (גרם)
const WEIGHT_ONLY_UNIT_ITEMS = {'שקד':1.2,'אגוז':4,'אגוזי מלך':4,'תמר':8,'זית':4,'צימוקים':1};
// כוסות של דגנים/קטניות - ממירים למשקל כי כך קונים בפועל (גרם לכוס, יבש)
const CUP_TO_GRAMS = {'אורז מלא':190,'אורז בסמטי':185,'אורז':185,'קינואה':170,'קינואה מבושלת':185,'שיבולת שועל':90,'אדממה':155};

function kgOrGrams(grams){
  grams = Math.ceil(grams/10)*10;
  if(grams>=1000){
    const kg = grams/1000;
    return (Number.isInteger(kg)?kg:kg.toFixed(1)) + ' ק"ג';
  }
  return grams + ' גרם';
}

function toShoppingDisplay(name, unit, total){
  // שקדים/אגוזים/תמרים/זיתים - כשיש כמות משמעותית, יותר שימושי לדעת כמה גרם לקנות
  // מאשר לספור "44 שקדים" (כשמדובר בכמות קטנה, ספירה עדיין סבירה)
  if(unit==='יחידה' && WEIGHT_ONLY_UNIT_ITEMS[name] && total>=10){
    return `${name} — כ-${kgOrGrams(total*WEIGHT_ONLY_UNIT_ITEMS[name])}`;
  }
  // כוסות דגנים/קטניות - המרה למשקל
  if(unit==='כוס' && CUP_TO_GRAMS[name]){
    return `${name} — כ-${kgOrGrams(total*CUP_TO_GRAMS[name])}`;
  }
  // כוסות חלב/משקה צמחי - המרה למ"ל/ליטר
  if(unit==='כוס' && (name.includes('חלב') || name.includes('משקה'))){
    let ml = Math.ceil(total*240/10)*10;
    const display = ml>=1000 ? (ml/1000).toFixed(1).replace(/\.0$/,'')+' ליטר' : ml+' מ"ל';
    return `${name} — כ-${display}`;
  }
  // פרוסות לחם - המרה לכיכרות (כיכר טיפוסית ~20 פרוסות) - כך באמת קונים לחם
  if(unit==='פרוסה' && name.includes('לחם')){
    const slicesNeeded = Math.ceil(total);
    const loaves = Math.ceil(slicesNeeded/20);
    return `${name} — ${loaves} ${loaves===1?'כיכר':'כיכרות'} (מספיק לכ-${slicesNeeded} פרוסות)`;
  }
  // גרם - קריא יותר בק"ג כשהכמות גדולה (עדיין נשאר לפי משקל, כי כך קונים בשר/גבינה בחנות)
  if(unit==='גרם' && total>=1000){
    return `${name} — ${kgOrGrams(total)}`;
  }
  // ברירת מחדל - יחידות ספירה רגילות (ירקות, ביצים, גביעים, קוביות...)
  const displayAmount = unit==='יחידה' ? Math.ceil(total) : total;
  const label = unitLabel(unit, displayAmount);
  return `${name} — ${formatAmount(displayAmount)} ${label}`;
}

/* ============================================================
   SHOPPING TAB - טווח תאריכים חופשי (לא בהכרח שבוע)
============================================================ */
async function getShoppingRange(){
  const saved = await sGet(`shopping-range:${CURRENT_PROFILE}`);
  if(saved) return saved;
  const start = getWeekStart();
  const end = addDays(start, 6);
  return {start: todayStr(start), end: todayStr(end)};
}
async function setShoppingRangePreset(daysAhead, daysLength){
  const start = addDays(getWeekStart(), daysAhead);
  const end = addDays(start, daysLength-1);
  const range = {start: todayStr(start), end: todayStr(end)};
  await sSet(`shopping-range:${CURRENT_PROFILE}`, range);
  renderShopping();
}
async function updateShoppingRangeFromInputs(){
  const start = document.getElementById('shop-range-start').value;
  const end = document.getElementById('shop-range-end').value;
  if(!start || !end || start > end){ showToast('טווח תאריכים לא תקין'); return; }
  await sSet(`shopping-range:${CURRENT_PROFILE}`, {start, end});
  renderShopping();
}

async function renderShopping(){
  const el = document.getElementById('tab-content');
  el.innerHTML = '<div class="card muted">בונה רשימת קניות...</div>';
  const range = await getShoppingRange();
  const startDate = new Date(range.start+'T00:00:00');
  const endDate = new Date(range.end+'T00:00:00');
  const dayCount = Math.round((endDate-startDate)/(1000*60*60*24)) + 1;
  const rangeKey = `${range.start}_${range.end}`;

  const profiles = PROFILES.length ? PROFILES : [CURRENT_PROFILE];
  const profileTiers = {};
  for(const p of profiles){
    const s = (await sGet(`settings:${p}`)) || {tier:1500};
    profileTiers[p] = s.tier;
  }

  // איסוף כל המרכיבים הגולמיים לטווח הנבחר:
  // - ארוחות משותפות (צהריים/ערב, כשלא סומן "בנפרד" לאותו יום): מנה אחת, אבל קונים
  //   לפי המנה של כל אחת מבני הבית (כל אחת לפי רמת הקלוריות שלה)
  // - ארוחות אישיות: כל אחת לפי הבחירה והרמה שלה
  const rawList = [];
  for(let i=0;i<dayCount;i++){
    const date = addDays(startDate,i);
    const dateStr = todayStr(date);
    const separate = await getSeparateDay(dateStr);
    const shared = await getSharedSelection(dateStr);
    for(const slot of SLOTS){
      const isShared = slot.shared && !separate && profiles.length>1;
      if(isShared){
        for(const p of profiles){
          const options = await allOptionsFor(profileTiers[p], slot.id);
          const selId = shared[slot.id] || options[0].id;
          const opt = options.find(o=>o.id===selId) || options[0];
          opt.ingredients.forEach(ing=> rawList.push(ing));
        }
      } else {
        for(const p of profiles){
          const menu = (await sGet(`menu:${p}:${dateStr}`)) || {};
          const options = await allOptionsFor(profileTiers[p], slot.id);
          const selId = menu[slot.id] || options[0].id;
          const opt = options.find(o=>o.id===selId) || options[0];
          opt.ingredients.forEach(ing=> rawList.push(ing));
        }
      }
    }
  }

  // איחוד: פריטים מכומתים נצברים לפי (שם+יחידה), פריטים לא-מכומתים נספרים כמו קודם
  const quantified = {}; // key: name|unit -> {name, unit, total}
  const generic = {}; // name -> count
  rawList.forEach(raw=>{
    const p = parseIngredient(raw);
    if(p.unit){
      const key = p.name+'|'+p.unit;
      if(!quantified[key]) quantified[key] = {name:p.name, unit:p.unit, total:0};
      quantified[key].total += p.amount;
    } else {
      generic[p.name] = (generic[p.name]||0)+1;
    }
  });

  const checks = (await sGet(`shopping-checks:${rangeKey}`)) || {};
  const pantry = await getPantryStaples();
  const pantrySet = new Set(pantry);
  const quantifiedItems = Object.values(quantified).sort((a,b)=>a.name.localeCompare(b.name,'he'));
  const genericItems = Object.keys(generic).sort((a,b)=>a.localeCompare(b,'he'));

  const quantifiedToBuy = quantifiedItems.filter(q=>!pantrySet.has(`${q.name}|${q.unit}`));
  const quantifiedInPantry = quantifiedItems.filter(q=>pantrySet.has(`${q.name}|${q.unit}`));
  const genericToBuy = genericItems.filter(n=>!pantrySet.has(`generic:${n}`));
  const genericInPantry = genericItems.filter(n=>pantrySet.has(`generic:${n}`));

  function rowHtml(displayText, itemKey, inPantry){
    const enc = encodeURIComponent(itemKey);
    return `
      <div class="shop-item ${checks[itemKey]?'checked':''}" data-ing="${enc}" style="${inPantry?'opacity:.6;':''}">
        <input type="checkbox" ${checks[itemKey]?'checked':''} onchange="toggleShopItem('${rangeKey}','${enc}', this.checked)">
        <span style="flex:1;">${displayText}</span>
        <button class="link-btn" style="font-size:11px;white-space:nowrap;" onclick="${inPantry?'removeFromPantry':'addToPantry'}('${enc}')">${inPantry?'החזרה לרשימה':'🏠 יש בבית'}</button>
      </div>`;
  }

  el.innerHTML = `
    <div class="card" style="padding:12px 16px;">
      <div style="font-weight:700;color:var(--primary-dark);margin-bottom:8px;">טווח תאריכים לרשימת הקניות</div>
      <div class="btn-row" style="margin-bottom:10px;">
        <button class="btn secondary" onclick="setShoppingRangePreset(0,7)">השבוע הזה</button>
        <button class="btn secondary" onclick="setShoppingRangePreset(7,7)">השבוע הבא</button>
        <button class="btn secondary" onclick="setShoppingRangePreset(0,14)">שבועיים מהיום</button>
      </div>
      <div class="btn-row">
        <div class="field" style="flex:1;margin-bottom:0;"><label>מתאריך</label><input type="date" id="shop-range-start" value="${range.start}"></div>
        <div class="field" style="flex:1;margin-bottom:0;"><label>עד תאריך</label><input type="date" id="shop-range-end" value="${range.end}"></div>
      </div>
      <button class="btn block" style="margin-top:10px;" onclick="updateShoppingRangeFromInputs()">עדכון טווח</button>
      <div class="muted" style="margin-top:8px;text-align:center;">${fmtDate(startDate)} - ${fmtDate(endDate)} (${dayCount} ימים)</div>
    </div>
    <div class="card">
      <h3>🛒 רשימת קניות</h3>
      <div class="muted" style="margin-bottom:8px;">כמויות מאוחדות ומסוכמות לפי התפריט בטווח שנבחר</div>
      <button class="btn secondary block" style="margin-bottom:10px;" onclick="printShoppingList()">🖨️ הדפסה / שמירה כ-PDF</button>
      ${quantifiedToBuy.map(q=>rowHtml(toShoppingDisplay(q.name, q.unit, q.total), `${q.name}|${q.unit}`, false)).join('')}
      ${genericToBuy.length ? `<div class="muted" style="margin:12px 0 6px;font-size:12px;">פריטים נוספים (כמות לפי הצורך)</div>` : ''}
      ${genericToBuy.map(name=>rowHtml(`${name}${generic[name]>1?' (נדרש '+generic[name]+' פעמים)':''}`, `generic:${name}`, false)).join('')}
      ${(!quantifiedToBuy.length && !genericToBuy.length) ? '<div class="muted">אין מה לקנות - הכל כבר יש בבית, או שלא נבחר תפריט 🎉</div>' : ''}
    </div>
    ${(quantifiedInPantry.length || genericInPantry.length) ? `
    <div class="card">
      <h3>🏠 כבר יש לנו בבית</h3>
      <div class="muted" style="margin-bottom:8px;">לא נכללים ברשימה למעלה - לחצו "החזרה לרשימה" אם נגמר</div>
      ${quantifiedInPantry.map(q=>rowHtml(toShoppingDisplay(q.name, q.unit, q.total), `${q.name}|${q.unit}`, true)).join('')}
      ${genericInPantry.map(name=>rowHtml(name, `generic:${name}`, true)).join('')}
    </div>` : ''}
  `;
}
async function getPantryStaples(){
  return (await sGet('pantry-staples')) || [];
}
async function addToPantry(encKey){
  const itemKey = decodeURIComponent(encKey);
  const list = await getPantryStaples();
  if(!list.includes(itemKey)) list.push(itemKey);
  await sSet('pantry-staples', list);
  showToast('סומן כ"יש בבית" 🏠');
  renderShopping();
}
async function removeFromPantry(encKey){
  const itemKey = decodeURIComponent(encKey);
  const list = await getPantryStaples();
  const idx = list.indexOf(itemKey);
  if(idx>-1) list.splice(idx,1);
  await sSet('pantry-staples', list);
  renderShopping();
}
